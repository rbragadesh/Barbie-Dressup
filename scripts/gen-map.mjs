// Builds js/data/worldmap.js. Inputs: world-atlas (Natural Earth 1:50m/1:110m, de facto borders)
// plus Natural Earth 1:10m "India point of view" for India, Pakistan and China, so India is shown
// with its official boundary (as required for maps used in India).
//
// Only needed if you change the map. In an empty folder:
//   npm i world-atlas@2 d3-geo@3 topojson-client@3 topojson-server@3 topojson-simplify@3
//   curl -o ind10.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries_ind.geojson
//   node -e "const g=require('./ind10.geojson');g.features=g.features.filter(f=>['India','Pakistan','China'].includes(f.properties.NAME));require('fs').writeFileSync('india10.json',JSON.stringify(g))"
//   node gen-map.mjs   (then copy worldmap.js to js/data/)
import fs from 'node:fs';
import { geoNaturalEarth1, geoPath, geoContains } from 'd3-geo';
import { feature } from 'topojson-client';
import { topology } from 'topojson-server';
import { presimplify, simplify, quantile } from 'topojson-simplify';
const load = f => JSON.parse(fs.readFileSync(f));
const simp = (topo, q) => { const p = presimplify(topo); return simplify(p, quantile(p, q)); };
const t110 = load('node_modules/world-atlas/countries-110m.json');
const t50 = load('node_modules/world-atlas/countries-50m.json');
const c110 = feature(t110, t110.objects.countries);
const c50 = feature(simp(t50, 0.25), t50.objects.countries);
const c50bg = feature(simp(t50, 0.12), t50.objects.countries);
const c50full = feature(t50, t50.objects.countries);
const indTopo = simp(topology({ c: load('india10.json') }), 0.03);
const indPov = feature(indTopo, indTopo.objects.c).features;
const pov = name => indPov.find(f => f.properties.NAME === name);
const W = 1000, H = 520;
const proj = geoNaturalEarth1().fitExtent([[5, 5], [W - 5, H - 5]], { type: 'Sphere' });
const path = geoPath(proj).digits(1);
const want = { IN: 'India', KR: 'South Korea', TW: 'Taiwan', SG: 'Singapore', ID: 'Indonesia', JP: 'Japan', FR: 'France', EG: 'Egypt', AU: 'Australia', BR: 'Brazil', US: 'United States of America', UK: 'United Kingdom', ES: 'Spain', AE: 'United Arab Emirates', TH: 'Thailand' };
const out = {};
for (const [code, name] of Object.entries(want)) {
  const f = code === 'IN' ? pov('India') : c50.features.find(f => f.properties.name === name);
  if (!f) throw new Error('missing ' + name);
  out[code] = path(f);
}
const indo = c50full.features.find(f => f.properties.name === 'Indonesia');
const bali = indo.geometry.coordinates.find(poly => geoContains({ type: 'Polygon', coordinates: poly }, [115.19, -8.4]));
out.BALI = path({ type: 'Polygon', coordinates: bali });
// Finer outlines where the map zooms in (Asia and Europe/Middle East).
const inAsia = f => { const [[x0, y0], [x1, y1]] = geoPath(proj).bounds(f); return (x1 > 650 && x0 < 960 && y0 < 330 && y1 > 90) || (x1 > 460 && x0 < 680 && y0 < 230 && y1 > 40); };
const skip = new Set([...Object.values(want), 'Antarctica', 'China', 'Pakistan']);
let world = path(pov('China')) + path(pov('Pakistan'));
for (const f of c50bg.features) if (inAsia(f) && !skip.has(f.properties.name)) world += path(f);
for (const f of c110.features) if (!inAsia(f) && !skip.has(f.properties.name)) world += geoPath(proj).digits(0)(f);
const pins = { IN: [77.21, 28.61], KR: [126.98, 37.57], TW: [121.56, 25.03], SG: [103.82, 1.35], BALI: [115.19, -8.65], JP: [139.69, 35.69], FR: [2.35, 48.86], EG: [31.24, 30.04], AU: [149.13, -35.28], BR: [-47.88, -15.79], US: [-74.0, 40.71], UK: [-1.8, 53.4], ES: [-3.70, 40.42], AE: [54.37, 24.45], TH: [100.50, 13.75] };
// Zoomed views as [x, y, w, h] in map units, from lon/lat corners.
const box = ([lon0, lat1], [lon1, lat0]) => { const [x0, y0] = proj([lon0, lat1]); const [x1, y1] = proj([lon1, lat0]); return [x0, y0, x1 - x0, y1 - y0].map(n => +n.toFixed(1)); };
const views = { asia: box([66, 46], [146, -12]), europe: box([-14, 64], [62, 16]), world: [0, 0, W, H] };
const pinXY = Object.fromEntries(Object.entries(pins).map(([k, v]) => [k, proj(v).map(n => +n.toFixed(1))]));
const js = `// Generated by scripts/gen-map.mjs from Natural Earth (public domain). Do not edit by hand.
// NaturalEarth1 projection fitted to ${W}x${H}. India uses Natural Earth's India point-of-view boundary.
export const MAP_W = ${W};
export const MAP_H = ${H};
export const SPHERE = ${JSON.stringify(path({ type: 'Sphere' }))};
export const WORLD = ${JSON.stringify(world)};
export const COUNTRY_SHAPES = ${JSON.stringify(out)};
export const PINS = ${JSON.stringify(pinXY)};
export const VIEWS = ${JSON.stringify(views)};
`;
fs.writeFileSync('worldmap.js', js);
console.log('total KB', (js.length / 1024).toFixed(0), 'IN', out.IN.length);
