// Regenerates sw.js with the current list of app files and a fresh cache name.
// Run after adding, removing or changing files: node scripts/build-sw.mjs
import fs from 'node:fs';
import path from 'node:path';

const walk = dir => fs.readdirSync(dir, { withFileTypes: true }).flatMap(d => d.isDirectory() ? walk(path.join(dir, d.name)) : [path.join(dir, d.name)]);
const files = [
  './', 'index.html', 'manifest.webmanifest',
  ...walk('icons'), ...walk('css'), ...walk('js'), ...walk('photos'),
].map(f => f.split(path.sep).join('/')).sort((a, b) => (a === './' ? -1 : b === './' ? 1 : a.localeCompare(b)));

const version = new Date().toISOString().slice(0, 16).replace(/[-:T]/g, '');
const sw = `// Offline support. Serves files from the cache straight away and refreshes the
// cache in the background, so the next launch picks up any update.
// Generated by scripts/build-sw.mjs: re-run it after changing app files.
const CACHE = 'dressup-world-tour-${version}';
const ASSETS = ${JSON.stringify(files, null, 2).replace(/"/g, "'")};

self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(caches.open(CACHE).then(async cache => {
    const hit = await cache.match(req, { ignoreSearch: true });
    const fresh = fetch(req)
      .then(res => { if (res.ok) cache.put(req, res.clone()); return res; })
      .catch(() => hit || cache.match('index.html'));
    return hit || fresh;
  }));
});
`;
fs.writeFileSync('sw.js', sw);
console.log(`sw.js: ${files.length} files, cache ${version}`);
